const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  presets: {
    list: () => ipcRenderer.invoke('presets:list'),
    save: (name, state) => ipcRenderer.invoke('presets:save', name, state),
    remove: (name) => ipcRenderer.invoke('presets:delete', name),
    exportFile: (name, state) => ipcRenderer.invoke('presets:exportFile', name, state),
    importFile: () => ipcRenderer.invoke('presets:importFile'),
  },
  fonts: {
    list: () => ipcRenderer.invoke('fonts:list'),
    import: () => ipcRenderer.invoke('fonts:import'),
    remove: (file) => ipcRenderer.invoke('fonts:remove', file),
    installData: (file, data) => ipcRenderer.invoke('fonts:installData', file, data),
    read: (file) => ipcRenderer.invoke('fonts:read', file),
    openManager: () => ipcRenderer.invoke('fonts:openManager'),
  },
  exporter: {
    chooseDest: (format, baseName, dir) => ipcRenderer.invoke('export:chooseDest', format, baseName, dir),
    chooseFolderDefault: () => ipcRenderer.invoke('export:chooseFolderDefault'),
    chooseFolder: () => ipcRenderer.invoke('export:chooseFolder'),
    pathIn: (dir, name, format) => ipcRenderer.invoke('export:pathIn', dir, name, format),
    start: (opts) => ipcRenderer.invoke('export:start', opts),
    frame: (id, data) => ipcRenderer.invoke('export:frame', id, data),
    finish: (id) => ipcRenderer.invoke('export:finish', id),
    cancel: (id) => ipcRenderer.invoke('export:cancel', id),
  },
  project: {
    save: (filePath, json, suggestedName) => ipcRenderer.invoke('project:save', filePath, json, suggestedName),
    open: () => ipcRenderer.invoke('project:open'),
    read: (p) => ipcRenderer.invoke('project:read', p),
    onOpenPath: (cb) => ipcRenderer.on('project:openPath', (_e, p) => cb(p)),
  },
  live: {
    start: (opts) => ipcRenderer.invoke('live:start', opts),
    stop: () => ipcRenderer.invoke('live:stop'),
    update: (state) => ipcRenderer.invoke('live:update', state),
    cue: (action) => ipcRenderer.invoke('live:cue', action),
    status: () => ipcRenderer.invoke('live:status'),
    onCued: (cb) => ipcRenderer.on('live:cued', (_e, a) => cb(a)),
  },
  mogrt: {
    findAE: () => ipcRenderer.invoke('mogrt:findAE'),
    chooseAE: () => ipcRenderer.invoke('mogrt:chooseAE'),
    run: (opts) => ipcRenderer.invoke('mogrt:export', opts),
    revealScript: (p) => ipcRenderer.invoke('mogrt:revealScript', p),
  },
  updates: {
    check: () => ipcRenderer.invoke('update:check'),
    open: (url) => ipcRenderer.invoke('shell:openExternal', url),
  },
  license: {
    status: () => ipcRenderer.invoke('license:status'),
    refresh: () => ipcRenderer.invoke('license:refresh'),
    activate: (key) => ipcRenderer.invoke('license:activate', key),
    deactivate: () => ipcRenderer.invoke('license:deactivate'),
  },
  files: {
    saveText: (opts) => ipcRenderer.invoke('files:saveText', opts),
    openText: (opts) => ipcRenderer.invoke('files:openText', opts),
  },
  help: { guide: (page) => ipcRenderer.invoke('help:guide', page) },
  diagnostics: () => ipcRenderer.invoke('app:diagnostics'),
  config: () => ipcRenderer.invoke('app:config'),
  closeWindow: () => ipcRenderer.invoke('app:close'),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd) => cb(cmd)),
  reveal: (p) => ipcRenderer.invoke('shell:reveal', p),
  info: () => ipcRenderer.invoke('app:info'),
});
